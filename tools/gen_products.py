# One-off: products_src.txt -> ../data/products.tsv (the TSV is the catalog source from now on).
import re, sys
TR = dict(zip('абвгдеёжзийклмнопрстуфхцчшщъыьэюя', ['a','b','v','g','d','e','e','zh','z','i','y','k','l','m','n','o','p','r','s','t','u','f','h','ts','ch','sh','sch','','y','','e','yu','ya']))
def slug(s): return 'p-' + re.sub(r'-+','-', re.sub(r'[^a-z0-9]+','-', ''.join(TR.get(c, c) for c in s.lower()))).strip('-')
PLUS2 = ['овощная смесь','гречк','бурый','булгур','киноа','овсян','перлов','пшено','цельнозерн','чечевиц','нут','фасоль','горох','черник','малин','смородин','клюкв','ягоды','треск','минтай','хек','судак','горбуш','сёмг','форел','скумбр','камбал','дорадо','сибас','тилапи','мидии','кальмар','креветк','брокколи','шпинат','капуста','кабач','цукини','морков','свёкл','тыкв','перец болгар','помидор','огур','салат','руккол','петруш','укроп','кинз','базилик','сельдер','спарж','баклажан','стручков','лук','чеснок','редис','редьк','грибы','шампиньон','вешенк','грецкие','миндаль','семена чиа','лён','тунец','авокадо','батат','квашен']
PLUS1 = ['хлеб ржаной','яблок','груш','апельсин','мандарин','киви','грейпфрут','гранат','персик','абрикос','слив','клубник','арбуз','дын','хурм','манго','ананас','банан','виноград','куриная грудка','индейк','курица','бёдра','голени','фарш куриный','фарш индейки','печень','яйцо','яйца','кефир','йогурт','творог 5','тофу','картоф','оливковое','телятин','фундук','кешью','кунжут','тыквенные','семечки','хумус','зелёный горошек','кукуруза','томаты в','ряженк','хлеб цельно','хлебцы','макароны цельно','лапша гречнев','сельдь','брынза','фета','моцарелла','оливки','чернослив','курага','мука цельно','растительное молоко','лимон','лайм','имбирь']
MINUS1 = ['свинин','свиная','баранин','фарш свино','масло сливочное','сметана','сливки 20','сыр плавлен','мёд','изюм','финики','батон','манная','кукурузные хлопья','гранола','шпроты','пельмени','тесто','сок','песто','творожный сыр','бульонный','мармелад','пастила','шоколад','батончик','кокосовое','крахмал','вермишель','лаваш','тортилья','сухари','рис белый','рис для плова','сливки 10']
MINUS2 = ['сосиски','колбаса','ветчин','бекон','сахар','майонез','кетчуп','сгущ','сырок','ванильный']
def quality(name, dept):
    n = name.lower()
    for k in MINUS2:
        if k in n: return -2
    for k in MINUS1:
        if k in n: return -1
    for k in PLUS2:
        if k in n: return 2
    for k in PLUS1:
        if k in n: return 1
    return 0
rows = []; seen = set()
for line in open('products_src.txt', encoding='utf-8'):
    line = line.strip()
    if not line or line.startswith('#'): continue
    p = line.split(';')
    if len(p) == 10: p.insert(9, "")
    assert len(p) == 11, line
    name, dept, kcal, pr, fa, ca, piece, yld, diet, flags, al = p
    i = slug(name); assert i not in seen, i; seen.add(i)
    rows.append([i, name, al, dept, kcal, pr, fa, ca, piece, yld, diet, flags, str(quality(name, dept)), '1795788000000'])
with open('../data/products.tsv', 'w', encoding='utf-8') as f:
    f.write('id\tname\taliases\tdept\tkcal\tprotein\tfat\tcarbs\tpiece_g\tyield\tdiet\tflags\tquality\tupdated\n')
    for r in rows: f.write('\t'.join(r) + '\n')
print(len(rows))
